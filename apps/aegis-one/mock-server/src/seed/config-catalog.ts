/**
 * The configuration-compliance check library.
 *
 * Extracted from the approved reference, not retyped: 120 Windows, 40 macOS
 * and 40 Linux checks, 200 in all, which is the figure the page's "Checks in
 * Scope" counter reports.
 *
 * `key` ties a check to a real inventory column, so a device that is actually
 * unencrypted fails the encryption check rather than a coin toss. The checks
 * without a key are spread deterministically from the device and check ids —
 * see `CHECK_PASS_SQL` in the seed.
 */

/** The four frameworks a check can be mapped to, as the contract names them. */
export type FrameworkRef = 'cis' | 'stig' | 'pci-dss' | 'hipaa';

export interface ConfigCheckDef {
  readonly id: string;
  readonly platform: 'windows' | 'macos' | 'linux';
  readonly category: string;
  readonly title: string;
  /** The value the check wants to see. */
  readonly expected: string;
  /** What a failing device reports instead. */
  readonly bad: string;
  readonly severity: 'high' | 'medium' | 'low';
  /** An inventory column this check reads, or '' to spread it by hash. */
  readonly key: string;
  readonly cis: string;
  readonly stig: string;
  readonly pci: string;
  readonly hipaa: string;
  /** False where the fix cannot be pushed and an administrator must act. */
  readonly remediable: boolean;
}

