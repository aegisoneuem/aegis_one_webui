/**
 * The report catalogue: the twenty standard reports the approved console
 * publishes, extracted from the reference rather than retyped.
 *
 * A report is a row source, an ordered column list and a handful of group-by
 * charts — which is exactly how the reference models one, and why twenty
 * reports need one engine rather than twenty implementations.
 *
 * Titles, descriptions, categories, units, chart group-bys and column order
 * are all the reference's. Only `source` and `filter` are ours: they say
 * which of this estate's tables a row comes from.
 */

/** The four categories the library counts, as the contract names them. */
export type ReportCategory = 'computers-software' | 'daily-operations' | 'security' | 'leadership';

/**
 * Which rows a report lists. Every source is a device joined to the records
 * the report is about, so every report carries the full device column set.
 */
export type ReportSource =
  | 'devices'
  | 'software'
  | 'licenses'
  | 'updates'
  | 'update-results'
  | 'issues'
  | 'usb'
  | 'deployments'
  | 'activity';

export interface ReportColumnDef {
  readonly field: string;
  readonly header: string;
}

/** One panel on the report: a count of rows grouped by one field. */
export interface ReportChartDef {
  readonly title: string;
  readonly field: string;
}

export interface ReportDef {
  readonly id: string;
  readonly title: string;
  readonly category: ReportCategory;
  readonly description: string;
  /** The noun the row count is measured in, e.g. "computers", "updates". */
  readonly unit: string;
  readonly source: ReportSource;
  /** Extra SQL narrowing the source, for a report that is not the whole estate. */
  readonly filter?: string;
  readonly charts: readonly ReportChartDef[];
  readonly columns: readonly ReportColumnDef[];
}

